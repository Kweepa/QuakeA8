#!/usr/bin/env python3
"""Pack assets/weapons/splat_0..2.png → src/splat_spr.asm (mode E).

24 hires pixels collapse to 12 colour columns at phase 0.
Ink is %11, clear is %00. 21 rows of 3 bytes.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from sprmask import (  # noqa: E402
    SH,
    SW,
    bchunk,
    load_png_1bit,
    pack_mode_e,
)

PNG_DIR = ROOT / "assets" / "weapons"
OUT = ROOT / "src" / "splat_spr.asm"
N = 3


def main() -> None:
    parts = [
        "; Auto-generated by tools/gensplat.py — do not edit\n",
        "; Mode E, phase 0: 21 rows × 3 bytes. Ink %11, clear %00.\n",
        "; 24 hires → 12 colour columns. Distance LOD 0 = near … 2 = far.\n",
        "; Source: assets/weapons/splat_0..2.png (ink centered for tip−12/−10)\n",
    ]
    sizes = []
    for i in range(N):
        path = PNG_DIR / f"splat_{i}.png"
        if not path.is_file():
            raise SystemExit(f"missing {path}")
        packed = pack_mode_e(load_png_1bit(path, SW, SH))
        sizes.append(len(packed))
        parts.append(f"spr_splat_{i}\n")
        parts.append(bchunk(packed))
        parts.append("\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} mode-E {sizes}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write src/smc_tags.asm — one global label per map-accessor expansion.

ACME 0.97 exports only global symbols, and a macro cannot build a label
name from a counter. Each accessor takes the next smc_N via this tree.
"""

from __future__ import annotations

from pathlib import Path

N = 1024  # power of two; raise if a build reports "out of smc_ tags"
OUT = Path(__file__).resolve().parents[1] / "src" / "smc_tags.asm"


def tree(lo: int, hi: int, indent: int) -> list[str]:
    if lo == hi:
        return [f"smc_{lo}"]
    mid = (lo + hi) // 2
    pad = "\t" * indent
    return [
        f"{pad}!if SMC_N <= {mid} {{",
        *tree(lo, mid, indent + 1),
        f"{pad}}} else {{",
        *tree(mid + 1, hi, indent + 1),
        f"{pad}}}",
    ]


def main() -> None:
    if N < 2 or N & (N - 1):
        raise SystemExit("SMC_TAG_N must be a power of two")
    lines = [
        "; Generated by tools/gen_smc_tags.py — do not edit.",
        "; Global smc_N labels. mkreloc and genaimeta patch only these.",
        f"SMC_TAG_N\t= {N}",
        "!set SMC_N = 0",
        "!macro smc_plant {",
        "\t!set SMC_N = SMC_N + 1",
        "\t!if SMC_N > SMC_TAG_N {",
        '\t\t!error "out of smc_ tags; raise N in tools/gen_smc_tags.py"',
        "\t}",
        *tree(1, N, 1),
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name} ({N} tags)")


if __name__ == "__main__":
    main()

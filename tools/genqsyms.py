#!/usr/bin/env python3
"""Export the GAME entry points and a8sio cells the QSAVE overlay uses."""

from __future__ import annotations

import argparse
from pathlib import Path

from mkreloc import parse_labels

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "qsyms.asm"

REQUIRED = [
    "qs_sector",
    "sio_sec_l",
    "sio_sec_h",
    "sio_dst_l",
    "sio_dst_h",
    "cheat_show",
    "set_room_idx",
    "update_floor",
    "sync_eye",
    "hud_ammo",
    "hud_powerup",
    "switch_weapon",
]


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate QSAVE overlay GAME symbols")
    ap.add_argument("--labels", default="game.lbl")
    args = ap.parse_args()
    path = Path(args.labels)
    if not path.is_file():
        path = ROOT / path
    labels = parse_labels(path)
    missing = [name for name in REQUIRED if name not in labels]
    if missing:
        raise SystemExit(f"{path}: missing quicksave symbols: {', '.join(missing)}")
    lines = ["; Generated by tools/genqsyms.py — GAME entries for the QSAVE overlay"]
    lines.extend(f"{name}\t= ${labels[name]:04x}" for name in REQUIRED)
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(REQUIRED)} symbols)")


if __name__ == "__main__":
    main()

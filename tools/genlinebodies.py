"""Emit unrolled mode-E line bodies into src/_a8line_bodies.asm."""
from pathlib import Path

# Mode E: four colour clocks per byte, linear 32-byte rows. No charset, no y=64.
A8_MASKS = [0xC0, 0x30, 0x0C, 0x03]
A8_OUT = Path(__file__).resolve().parents[1] / "src" / "_a8line_bodies.asm"


def y_step(down: bool) -> str:
    """±32 on colptr via ey_dn/ey_up. Clobbers A. C=1 on entry and exit."""
    return "\tjsr ey_dn\n" if down else "\tjsr ey_up\n"


def y_subs() -> str:
    # Every caller arrives with C=1: the error update's adc always wraps (the
    # true sum e-d1+d2 >= 0 with d2 >= d1), and dex/inc/lda/ora/sta keep C.
    return """; C=1 on entry and exit
ey_dn
	lda colptr
	adc #31
	sta colptr
	bcc ey_dn1
	inc colptr+1
	rts
ey_dn1
	sec
	rts
ey_up
	lda colptr
	sbc #32
	sta colptr
	bcs ey_up1
	dec colptr+1
	sec
ey_up1
	rts
"""


def byte_inc(tag: str) -> str:
    return f"""	inc colptr
	bne {tag}
	inc colptr+1
{tag}
"""


def shallow(prefix: str, down: bool) -> str:
    parts: list[str] = []
    for i, mask in enumerate(A8_MASKS):
        n = f"{prefix}{i}"
        nxt = f"{prefix}{(i + 1) & 3}"
        step = y_step(down)
        if i < 3:
            tail = f"""	sta err_l
{step}	jmp {nxt}
{n}sk
	sta err_l
"""
        else:
            tail = f"""	sta err_l
{step}	jmp {n}x
{n}sk
	sta err_l
{n}x
{byte_inc(n + "nb")}	jmp {prefix}0
"""
        parts.append(
            f"""{n}
	lda (colptr),y
	ora #${mask:02x}
	sta (colptr),y
	dex
	bne {n}c
	rts
{n}c
	lda err_l
	sbc dy
	bcs {n}sk
	adc dx
{tail}"""
        )
    return "".join(parts)


def steep(prefix: str, down: bool) -> str:
    parts: list[str] = []
    for i, mask in enumerate(A8_MASKS):
        n = f"{prefix}{i}"
        step = y_step(down)
        if i < 3:
            xstep = ""
        else:
            xstep = f"""	sta err_l
{byte_inc(n + "nb")}	jmp {prefix}0
"""
        parts.append(f"{n}s\n\tsta err_l\n")
        parts.append(
            f"""{n}
	lda (colptr),y
	ora #${mask:02x}
	sta (colptr),y
	dex
	bne {n}c
	rts
{n}c
{step}	lda err_l
	sbc dx
	bcs {n}s
	adc dy
"""
        )
        if i == 3:
            parts.append(xstep)
    return "".join(parts)


def a8_table(name: str, prefix: str) -> str:
    lo = ",".join(f"<{prefix}{i}" for i in range(4))
    hi = ",".join(f">{prefix}{i}" for i in range(4))
    return f"{name}_l\t!byte {lo}\n{name}_h\t!byte {hi}\n"


def emit_a8() -> None:
    parts = [
        "; Auto-generated by tools/genlinebodies.py — mode-E line bodies\n",
        "; Four masks, chained C, countdown in X. Y stays 0.\n",
        "; A row is ±32 on colptr (ey_dn/ey_up). Four pixels then colptr+1. No y=64 split.\n",
        y_subs(),
        "; ---- X major +Y ----\n",
        a8_table("esdn", "esd"),
        shallow("esd", True),
        "; ---- X major -Y ----\n",
        a8_table("esup", "esu"),
        shallow("esu", False),
        "; ---- Y major +Y ----\n",
        a8_table("etdn", "etd"),
        steep("etd", True),
        "; ---- Y major -Y ----\n",
        a8_table("etup", "etu"),
        steep("etu", False),
    ]
    A8_OUT.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {A8_OUT}")


def main() -> None:
    emit_a8()


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Spinning Q for the Atari menu: src/menu_cursor_spr.asm → src/a8_cursor_tab.asm.

The C64 Q is four 24×21 hires layers (white, lt grey, grey, black; layer 0 in
front). The Atari splits each hires line into:

  - P0+P1 (left 8 colour clocks) and P2+P3 (right 4), multicolour OR, so each
    clock is one of 0, CA, CB, CA|CB.
  - Missiles as the fifth player, double width, PF3 = black: a plate under the
    Q so the row's PF2 hue never shows through.
  - Three mode-2 glyphs per text row under the players. A set bit takes PF1's
    luminance on top of whatever the player shows, at hires.

PF1 differs per text row (blank, yellow item, white selected item), so every
line is solved for each luminance in LUMS. The menu picks the one that matches
the row at run time.
"""
from __future__ import annotations

import itertools
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "menu_cursor_spr.asm"
OUT = ROOT / "src" / "a8_cursor_tab.asm"

FRAMES = 6
LINES = 21
CLOCKS = 12
LAYER_LUM = (14, 12, 8, 0)		# C64 white, lt grey, grey, black
LUMS = (0, 12, 14)				# blank row, yellow item, selected item


def load_layers() -> list[list[list[int | None]]]:
	text = SRC.read_text(encoding="utf-8")
	body = text.split("menu_cursor_spr", 1)[1]
	data = [int(h, 16) for h in re.findall(r"\$([0-9a-fA-F]{2})", body)]
	if len(data) < FRAMES * 256:
		raise SystemExit(f"{SRC.name}: expected {FRAMES * 256} bytes, got {len(data)}")
	frames = []
	for f in range(FRAMES):
		img = []
		for y in range(LINES):
			row: list[int | None] = []
			for x in range(24):
				lum = None
				for layer in range(4):
					b = data[f * 256 + layer * 64 + y * 3 + (x >> 3)]
					if b & (0x80 >> (x & 7)):
						lum = LAYER_LUM[layer]
						break
				row.append(lum)
			img.append(row)
		# Line 0 holds only sheet bleed (frame 0: stray pixels above the Q).
		img[0] = [None] * 24
		frames.append(img)
	return frames


BG_LUM = 4		# brown option box
HUE_PEN = 16	# paper hue showing where grey was wanted, or the reverse


def pixel_err(want, pm, g, row_lum, shades, plate):
	"""want None = transparent (paper should show)."""
	if g:
		covered = pm or plate
		if want is None:
			return (row_lum - BG_LUM) ** 2 + (0 if not covered else HUE_PEN)
		return (row_lum - want) ** 2 + (0 if covered else HUE_PEN)
	if pm or plate:
		disp = shades[pm] if pm else 0
		if want is None:
			return (disp - BG_LUM) ** 2 + HUE_PEN
		return (disp - want) ** 2
	if want is None:
		return 0
	return (BG_LUM - want) ** 2 + HUE_PEN


def solve_clock(t0, t1, row_lum, shades, plate):
	"""Best (player mask, glyph bits) for one colour clock. Returns (err, pm, g)."""
	best = None
	for pm in (0, 1, 2, 3):
		for g in (0, 2, 1, 3):
			err = pixel_err(t0, pm, g & 2, row_lum, shades, plate) + pixel_err(
				t1, pm, g & 1, row_lum, shades, plate
			)
			if best is None or err < best[0]:
				best = (err, pm, g)
	return best


def pick_plate(px, shades) -> int:
	"""Plate cells (2 clocks) chosen per line, shared by every row luminance."""
	plate = 0
	for cell in range(6):
		cost = []
		for on in (False, True):
			e = 0
			for lum in LUMS:
				for c in (cell * 2, cell * 2 + 1):
					e += solve_clock(px[2 * c], px[2 * c + 1], lum, shades, on)[0]
			cost.append(e)
		if cost[1] < cost[0]:
			plate |= 1 << (5 - cell)
	return plate


def solve_line(px, row_lum, shades, plate=None):
	err = 0
	p = [0, 0]			# CA layer, CB layer: 12 bits, bit 11 = clock 0
	glyph = 0			# 24 bits, bit 23 = hires 0
	if plate is None:
		plate = pick_plate(px, shades)	# 6 cells of 2 clocks
	for c in range(CLOCKS):
		covered = bool(plate & (1 << (5 - c // 2)))
		e, pm, g = solve_clock(px[2 * c], px[2 * c + 1], row_lum, shades, covered)
		err += e
		if pm & 1:
			p[0] |= 1 << (11 - c)
		if pm & 2:
			p[1] |= 1 << (11 - c)
		glyph |= g << (22 - 2 * c)
	return err, p, glyph, plate


def total_error(frames, ca, cb):
	shades = (0, ca, cb, ca | cb)
	return sum(
		solve_line(line, lum, shades)[0]
		for img in frames
		for line in img
		for lum in LUMS
	)


def missile_byte(plate: int) -> int:
	# Cell 0..5, M0 = cells 0-1 (bits 1,0), M1 = 2-3 (3,2), M2 = 4-5 (5,4).
	out = 0
	for cell in range(6):
		if plate & (1 << (5 - cell)):
			m = cell // 2
			hi = cell % 2 == 0
			out |= 1 << (m * 2 + (1 if hi else 0))
	return out


def fmt(data, per=18):
	return [
		"\t!byte " + ",".join(f"${b:02x}" for b in data[i : i + per])
		for i in range(0, len(data), per)
	]


def main() -> None:
	frames = load_layers()
	evens = range(2, 15, 2)
	best = None
	for ca, cb in itertools.combinations(evens, 2):
		if ca | cb in (ca, cb):
			continue
		e = total_error(frames, ca, cb)
		if best is None or e < best[0]:
			best = (e, ca, cb)
	_e, ca, cb = best
	shades = (0, ca, cb, ca | cb)

	lines = [
		"; Auto-generated by tools/gen_a8_cursor.py from menu_cursor_spr.asm",
		f"A8CUR_CA\t= ${ca:02x}\t\t; P0/P2",
		f"A8CUR_CB\t= ${cb:02x}\t\t; P1/P3 (overlap ${ca | cb:02x})",
		"; Per frame, per line, per row luminance (0, C, E):",
		";   a8ct_p: P0, P1, P2 hi nibble | P3 lo nibble",
		";   a8ct_g: glyph bytes for the three text columns",
		"; a8ct_m: per frame, per line, missile plate byte",
		"",
	]
	ptabs: list[list[int]] = []
	gtabs: list[list[int]] = []
	mtabs: list[list[int]] = []
	for img in frames:
		pt: list[int] = []
		gt: list[int] = []
		mt: list[int] = []
		for line in img:
			plate_b = 0
			for lum in LUMS:
				_err, p, glyph, plate = solve_line(line, lum, shades)
				p0 = (p[0] >> 4) & 0xFF
				p1 = (p[1] >> 4) & 0xFF
				p23 = ((p[0] & 0x0F) << 4) | (p[1] & 0x0F)
				pt += [p0, p1, p23]
				gt += [(glyph >> 16) & 0xFF, (glyph >> 8) & 0xFF, glyph & 0xFF]
				plate_b = missile_byte(plate)
			mt.append(plate_b)
		ptabs.append(pt)
		gtabs.append(gt)
		mtabs.append(mt)

	for name, tabs in (("p", ptabs), ("g", gtabs), ("m", mtabs)):
		lines.append(f"a8ct_{name}lo\t!byte " + ",".join(f"<a8ct_{name}{f}" for f in range(FRAMES)))
		lines.append(f"a8ct_{name}hi\t!byte " + ",".join(f">a8ct_{name}{f}" for f in range(FRAMES)))
	lines.append("")
	for name, tabs in (("p", ptabs), ("g", gtabs), ("m", mtabs)):
		for f, tab in enumerate(tabs):
			lines.append(f"a8ct_{name}{f}")
			lines.extend(fmt(tab))
		lines.append("")

	OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
	write_preview(frames, shades)
	print(f"wrote {OUT.relative_to(ROOT)} CA=${ca:02x} CB=${cb:02x} err={best[0]} + {PREVIEW.relative_to(ROOT)}")


PREVIEW = ROOT / "ui" / "a8_cursor_preview.png"


def write_preview(frames, shades) -> None:
	"""Rows: C64 source, then Atari on a selected row, a yellow row, a blank row."""
	from PIL import Image

	sx, sy = 4, 2			# hires pixel is half a colour clock wide
	cw = 24 * sx + 8
	ch = LINES * sy + 6
	brown = (100, 60, 20)
	im = Image.new("RGB", (cw * FRAMES, ch * 4), brown)
	px = im.load()

	def grey(lum):
		v = lum * 255 // 14
		return (v, v, v)

	def orange(lum):
		v = lum * 255 // 14
		return (v, v * 3 // 4, v // 3)

	def put(fx, fy, x, y, rgb):
		for dy in range(sy):
			for dx in range(sx):
				px[fx * cw + x * sx + dx, fy * ch + y * sy + dy] = rgb

	for f, img in enumerate(frames):
		for y, line in enumerate(img):
			for x, lum in enumerate(line):
				put(f, 0, x, y, brown if lum is None else grey(lum))
			for k, lum in enumerate((14, 12, 0)):
				_e, p, glyph, plate = solve_line(line, lum, shades)
				for x in range(24):
					c = x >> 1
					pm = ((p[0] >> (11 - c)) & 1) | (((p[1] >> (11 - c)) & 1) << 1)
					g = (glyph >> (23 - x)) & 1
					covered = bool(plate & (1 << (5 - x // 4)))
					if g:
						rgb = grey(lum) if pm or covered else orange(lum)
					elif pm:
						rgb = grey(shades[pm])
					elif covered:
						rgb = (0, 0, 0)
					else:
						rgb = brown
					put(f, k + 1, x, y, rgb)
	im.save(PREVIEW)


if __name__ == "__main__":
	main()
